_ADF_OUT = {"copy": "Copy", "sql": "Script", "mapping": "ExecuteDataFlow",
            "notebook": "DatabricksNotebook", "command": "WebActivity",
            "email": "WebActivity", "wait": "Wait",
            "choice": "IfCondition", "loop": "ForEach",
            "subworkflow": "ExecutePipeline", "sensor": "Validation",
            "dummy": "Wait", "parallel": "Wait", "approval": "WebHook",
            "unknown": "WebActivity"}


def _adf_ts(seconds: int) -> str:
    d, rem = divmod(seconds, 86400)
    h, rem = divmod(rem, 3600)
    m, s = divmod(rem, 60)
    return "%d.%02d:%02d:%02d" % (d, h, m, s)


def generate_adf(wf: Workflow, platform: str = "adf") -> Dict[str, dict]:
    acts = []
    for t in wf.tasks:
        deps = [{"activity": d.from_task,
                 "dependencyConditions": [
                     {"success": "Succeeded", "failure": "Failed",
                      "always": "Completed",
                      "conditional": "Succeeded",
                      "event": "Succeeded"}[d.kind]]}
                for d in wf.dependencies if d.to_task == t.key]
        atype = _ADF_OUT.get(t.type, "WebActivity")
        act: Dict[str, object] = {
            "name": t.name[:55] or t.key, "type": atype,
            "dependsOn": deps,
            "policy": {"retry": t.retry.max_attempts,
                       "retryIntervalInSeconds":
                           t.retry.interval_seconds or 30,
                       "timeout": _adf_ts(t.timeout_seconds or 7 * 86400)},
            "typeProperties": {},
        }
        tp: Dict[str, object] = act["typeProperties"]  # type: ignore
        if t.type == "sql":
            tp["scripts"] = [{"type": "Query",
                              "text": str(t.action.get("sql", "-- TODO"))}]
        elif t.type == "subworkflow":
            tp["pipeline"] = {"referenceName":
                              str(t.action.get("workflow", "TODO")),
                              "type": "PipelineReference"}
        elif t.type == "wait" or t.type in ("dummy", "parallel"):
            tp["waitTimeInSeconds"] = int(t.action.get("seconds", 1) or 1)
        elif t.type == "choice":
            tp["expression"] = {"value": t.condition or "@bool(true)",
                                "type": "Expression"}
            act["_metabridge_note"] = ("branch children must be nested "
                                       "into ifTrue/ifFalseActivities — "
                                       "see execution documentation")
        elif t.type == "loop":
            tp["items"] = {"value": str(t.loop.get("items",
                                                   "@pipeline().parameters"
                                                   ".items")),
                           "type": "Expression"}
            tp["isSequential"] = not t.loop.get("parallel", True)
        elif t.type in ("command", "email", "unknown"):
            tp["url"] = "https://TODO.invoke"
            tp["method"] = "POST"
            act["_metabridge_note"] = ("source task '%s' (%s): %s — port "
                                       "the payload to a native activity"
                                       % (t.key, t.type,
                                          json.dumps(t.action)[:150]))
        acts.append(act)
    pipeline = {"name": wf.name,
                "properties": {
                    "description": "Generated by MetaBridge AI from %s"
                                   % wf.platform,
                    "activities": acts,
                    "parameters": {v["name"]: {"type": "string",
                                               "defaultValue":
                                                   v.get("value", "")}
                                   for v in wf.variables
                                   if v.get("scope") == "parameter"},
                    "annotations": ["metabridge", wf.platform],
                }}
    out = {"%s_pipeline.json" % wf.name: pipeline}
    cron = _cron_of(wf)
    if cron:
        parts = cron.split()
        rec: Dict[str, object] = {"frequency": "Day", "interval": 1,
                                  "timeZone": "UTC"}
        if parts[1] != "*" and parts[0] != "*":
            rec["schedule"] = {"hours": [int(parts[1].split(",")[0])
                                         if parts[1].isdigit() else 0],
                               "minutes": [int(parts[0])
                                           if parts[0].isdigit() else 0]}
        trigger = {"name": "trg_%s" % wf.name,
                   "properties": {
                       "type": "ScheduleTrigger",
                       "typeProperties": {"recurrence": rec},
                       "pipelines": [{"pipelineReference": {
                           "referenceName": wf.name,
                           "type": "PipelineReference"}}],
                       "_metabridge_source_schedule": cron}}
        out["trg_%s.json" % wf.name] = trigger
    return out


