_AF_OP = {"command": ("BashOperator", "bash_command"),
          "sql": ("SQLExecuteQueryOperator", "sql"),
          "mapping": ("BashOperator", "bash_command"),
          "copy": ("BashOperator", "bash_command"),
          "notebook": ("BashOperator", "bash_command"),
          "email": ("EmailOperator", None),
          "dummy": ("EmptyOperator", None),
          "wait": ("TimeDeltaSensor", None),
          "sensor": ("FileSensor", None),
          "subworkflow": ("TriggerDagRunOperator", None)}


def generate_airflow(wf: Workflow) -> str:
    cron = _cron_of(wf)
    lines = [
        '"""%s — generated by MetaBridge AI from %s.' % (wf.name,
                                                         wf.platform),
        "",
        "Scheduling, retries, timeouts, dependency kinds and failure",
        'paths carry over from the source; review _metabridge notes."""',
        "from datetime import timedelta",
        "from airflow import DAG",
        "from airflow.operators.bash import BashOperator",
        "from airflow.operators.empty import EmptyOperator",
        "from airflow.operators.email import EmailOperator",
        "from airflow.operators.trigger_dagrun import TriggerDagRunOperator",
        "from airflow.providers.common.sql.operators.sql import "
        "SQLExecuteQueryOperator",
        "from airflow.sensors.filesystem import FileSensor",
        "from airflow.sensors.time_delta import TimeDeltaSensor",
        "",
        "with DAG(",
        '    dag_id="%s",' % wf.name,
        '    schedule=%s,' % (repr(cron) if cron else "None"),
        "    catchup=False,",
        '    tags=["metabridge", "%s"],' % wf.platform,
        ") as dag:",
    ]
    failure_targets = {d.to_task for d in wf.dependencies
                       if d.kind == "failure"}
    for t in wf.tasks:
        op, payload_kw = _AF_OP.get(t.type, ("BashOperator",
                                             "bash_command"))
        var = _pyid(t.key)
        args = ['task_id="%s"' % t.key]
        if t.type in ("choice", "loop", "parallel", "approval",
                      "unknown"):
            op = "EmptyOperator"
            note = {"choice": "branch — port the condition as a "
                              "BranchPythonOperator",
                    "loop": "loop — port as dynamic task mapping "
                            "(.expand())",
                    "parallel": "parallel group container",
                    "approval": "approval gate — no Airflow-native "
                                "equivalent; use an external approval "
                                "sensor",
                    "unknown": "unsupported source task — port manually"}
            lines.append("    # MANUAL: %s (%s)" % (note[t.type], t.key))
        if op == "BashOperator":
            payload = str(t.action.get("command", "")
                          or t.action.get("mapping", "")
                          or t.action.get("notebook", "")
                          or "echo TODO_%s" % t.key)
            args.append("bash_command=%r" % payload[:300])
        elif op == "SQLExecuteQueryOperator":
            args.append("sql=%r" % str(t.action.get("sql",
                                                    "-- TODO"))[:300])
            if t.connection:
                args.append('conn_id="%s"' % t.connection)
        elif op == "EmailOperator":
            args.append('to="%s"' % str(t.action.get("to",
                                                     "oncall@example.com")))
            args.append('subject="%s failed"' % wf.name)
        elif op == "TriggerDagRunOperator":
            args.append('trigger_dag_id="%s"'
                        % str(t.action.get("workflow", "TODO")))
        elif op == "TimeDeltaSensor":
            args.append("delta=timedelta(seconds=%d)"
                        % int(t.action.get("seconds", 60) or 60))
        elif op == "FileSensor":
            args.append('filepath="%s"'
                        % str(t.action.get("filepath", "/tmp/ready")))
        if t.retry.max_attempts:
            args.append("retries=%d" % t.retry.max_attempts)
            if t.retry.interval_seconds:
                args.append("retry_delay=timedelta(seconds=%d)"
                            % t.retry.interval_seconds)
        if t.timeout_seconds:
            args.append("execution_timeout=timedelta(seconds=%d)"
                        % t.timeout_seconds)
        if t.sla_seconds:
            args.append("sla=timedelta(seconds=%d)" % t.sla_seconds)
        if t.resources.get("pool"):
            args.append('pool="%s"' % t.resources["pool"])
        if t.key in failure_targets:
            args.append('trigger_rule="one_failed"')
        lines.append("    %s = %s(%s)" % (var, op, ", ".join(args)))
    lines.append("")
    for d in wf.dependencies:
        lines.append("    %s >> %s%s" % (
            _pyid(d.from_task), _pyid(d.to_task),
            "  # %s%s" % (d.kind, ": " + d.condition[:80]
                          if d.condition else "")
            if d.kind != "success" else ""))
    return "\n".join(lines) + "\n"


