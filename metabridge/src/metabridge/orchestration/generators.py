def generate_controlm(wf: Workflow) -> dict:
    folder: Dict[str, object] = {"Type": "Folder"}
    for t in wf.tasks:
        job: Dict[str, object] = {
            "Type": {"sql": "Job:Database:SQLScript",
                     "copy": "Job:FileTransfer",
                     "dummy": "Job:Dummy"}.get(t.type, "Job:Command")}
        cmd = str(t.action.get("command", "")
                  or t.action.get("mapping", ""))
        if job["Type"] == "Job:Command":
            job["Command"] = cmd or "echo TODO_%s" % t.key
        if t.retry.max_attempts:
            job["RerunLimit"] = {"Times": str(t.retry.max_attempts)}
        if t.resources.get("machine"):
            job["Host"] = t.resources["machine"]
        cron = _cron_of(wf)
        if cron:
            job["When"] = {"Schedule": "EVERYDAY",
                           "_metabridge_source_cron": cron}
        ins = [d for d in wf.dependencies if d.to_task == t.key]
        if ins:
            job["eventsToWaitFor"] = {
                "Type": "WaitForEvents",
                "Events": [{"Event": "%s_%s"
                            % (d.from_task, "OK" if d.kind != "failure"
                               else "FAILED")} for d in ins]}
        outs = [d for d in wf.dependencies if d.from_task == t.key]
        if outs:
            job["eventsToAdd"] = {
                "Type": "AddEvents",
                "Events": [{"Event": "%s_OK" % t.key}]}
            if any(d.kind == "failure" for d in outs):
                job["_metabridge_note"] = ("failure path: add an On/Do "
                                           "action raising %s_FAILED"
                                           % t.key)
        folder[t.key] = job
    return {wf.name: folder}


def generate_autosys(wf: Workflow) -> str:
    lines = ["/* %s — generated by MetaBridge AI from %s */"
             % (wf.name, wf.platform)]
    box = _pyid(wf.name).upper() + "_BOX"
    cron = _cron_of(wf)
    lines += ["", "insert_job: %s   job_type: b" % box]
    if cron:
        parts = cron.split()
        lines.append("date_conditions: 1")
        if parts[1].isdigit() and parts[0].isdigit():
            lines.append('start_times: "%02d:%02d"'
                         % (int(parts[1]), int(parts[0])))
        lines.append("/* source cron: %s */" % cron)
    for t in wf.tasks:
        lines += ["", "insert_job: %s   job_type: c" % _pyid(t.key).upper(),
                  "box_name: %s" % box]
        cmd = str(t.action.get("command", "")
                  or t.action.get("mapping", "")
                  or "echo TODO_%s" % t.key)
        lines.append("command: %s" % cmd[:200])
        conds = []
        for d in wf.dependencies:
            if d.to_task == t.key:
                fn = "f" if d.kind == "failure" else \
                    "d" if d.kind == "always" else "s"
                conds.append("%s(%s)" % (fn, _pyid(d.from_task).upper()))
        if conds:
            lines.append("condition: %s" % " & ".join(conds))
        if t.retry.max_attempts:
            lines.append("n_retrys: %d" % t.retry.max_attempts)
        if t.timeout_seconds:
            lines.append("term_run_time: %d"
                         % max(1, t.timeout_seconds // 60))
        if t.sla_seconds:
            lines.append("max_run_alarm: %d" % max(1, t.sla_seconds // 60))
        if t.type in ("choice", "loop", "approval", "unknown"):
            lines.append("/* MANUAL: %s task — no JIL equivalent, review */"
                         % t.type)
    return "\n".join(lines) + "\n"


def generate_dbtcloud(wf: Workflow) -> dict:
    steps = []
    for k in wf.execution_order():
        t = wf.task(k)
        if t is None:
            continue
        cmd = str(t.action.get("command", "") or t.action.get("sql", ""))
        steps.append(cmd if cmd.startswith("dbt") else
                     "# %s (%s): %s" % (t.key, t.type, cmd or "TODO"))
    job = {"name": wf.name,
           "execute_steps": steps,
           "triggers": {"schedule": bool(_cron_of(wf))},
           "settings": {"threads": 4},
           "_metabridge_note": "dbt Cloud runs steps SEQUENTIALLY — "
                               "parallel waves from the source are "
                               "serialized here."}
    cron = _cron_of(wf)
    if cron:
        job["schedule"] = {"cron": cron}
    return job


