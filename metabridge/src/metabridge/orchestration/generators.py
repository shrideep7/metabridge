def generate_powercenter_workflow(wf: Workflow) -> str:
    from xml.sax.saxutils import quoteattr
    tasks_xml, links_xml = [], []
    tasks_xml.append('    <TASK NAME="Start" TYPE="Start"/>')
    heads = {t.key for t in wf.tasks} - {d.to_task
                                         for d in wf.dependencies}
    for t in wf.tasks:
        ptype = {"mapping": "Session", "command": "Command",
                 "email": "Email", "choice": "Decision",
                 "wait": "Timer", "sensor": "Event-Wait",
                 "subworkflow": "Worklet"}.get(t.type, "Command")
        tasks_xml.append('    <TASK NAME=%s TYPE="%s"/>'
                         % (quoteattr(t.key), ptype))
    for h in sorted(heads):
        links_xml.append('    <TASKLINK FROMTASK="Start" TOTASK=%s/>'
                         % quoteattr(h))
    for d in wf.dependencies:
        cond = ' CONDITION=%s' % quoteattr(
            "$%s.Status = FAILED" % d.from_task) \
            if d.kind == "failure" else ""
        links_xml.append('    <TASKLINK FROMTASK=%s TOTASK=%s%s/>'
                         % (quoteattr(d.from_task), quoteattr(d.to_task),
                            cond))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            "<!-- Generated by MetaBridge AI from %s — session/mapping\n"
            "     bindings must be attached in the repository -->\n"
            '<POWERMART>\n  <REPOSITORY>\n  <FOLDER NAME="MetaBridge">\n'
            '  <WORKFLOW NAME=%s ISENABLED="YES">\n%s\n%s\n'
            "  </WORKFLOW>\n  </FOLDER>\n  </REPOSITORY>\n</POWERMART>\n"
            % (wf.platform, quoteattr(wf.name),
               "\n".join(tasks_xml), "\n".join(links_xml)))


def generate_idmc_taskflow(wf: Workflow) -> dict:
    succ: Dict[str, List] = {}
    for d in wf.dependencies:
        succ.setdefault(d.from_task, []).append(d)
    steps = []
    for t in wf.tasks:
        step: Dict[str, object] = {
            "name": t.key,
            "taskType": {"mapping": "MTT", "command": "CMD",
                         "choice": "DECISION", "wait": "WAIT",
                         "email": "NOTIFICATION",
                         "parallel": "PARALLEL_PATHS",
                         "subworkflow": "SUBTASKFLOW"}.get(t.type, "CMD")}
        if t.action.get("mapping"):
            step["mappingTask"] = str(t.action["mapping"])
        if t.retry.max_attempts:
            step["maxRetries"] = t.retry.max_attempts
        nexts = [d for d in succ.get(t.key, []) if d.kind != "failure"]
        fails = [d for d in succ.get(t.key, []) if d.kind == "failure"]
        if nexts:
            step["onSuccess"] = nexts[0].to_task
            if len(nexts) > 1:
                step["_metabridge_note"] = ("fans out to %s — use "
                                            "parallel paths"
                                            % [d.to_task
                                               for d in nexts[1:]])
        if fails:
            step["onFailure"] = fails[0].to_task
        if t.type == "unknown":
            step["_metabridge_note"] = "unsupported source task — review"
        steps.append(step)
    doc = {"name": wf.name,
           "description": "Generated by MetaBridge AI from %s"
                          % wf.platform,
           "taskflow": {"steps": steps}}
    cron = _cron_of(wf)
    if cron:
        doc["schedule"] = {"cron": cron}
    return doc


