def generate_orchestration(cor: COR, target: str, out_dir: str) -> dict:
    """COR -> target artifacts on disk. Returns the artifact manifest."""
    from pathlib import Path
    import yaml
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    written: List[str] = []

    def w(name: str, content: str) -> None:
        (out / name).write_text(content)
        written.append(name)

    for wf in cor.workflows:
        if target == "airflow":
            w("dag_%s.py" % wf.name, generate_airflow(wf))
        elif target in ("adf", "fabric"):
            for fname, doc in generate_adf(wf, target).items():
                w(fname, json.dumps(doc, indent=2) + "\n")
        elif target == "stepfunctions":
            w("%s.asl.json" % wf.name,
              json.dumps(generate_stepfunctions(wf), indent=2) + "\n")
        elif target == "controlm":
            w("%s.controlm.json" % wf.name,
              json.dumps(generate_controlm(wf), indent=2) + "\n")
        elif target == "autosys":
            w("%s.jil" % wf.name, generate_autosys(wf))
        elif target == "dbtcloud":
            w("%s.dbtcloud.json" % wf.name,
              json.dumps(generate_dbtcloud(wf), indent=2) + "\n")
        elif target == "powercenter":
            w("wf_%s.xml" % wf.name, generate_powercenter_workflow(wf))
        elif target == "idmc_taskflow":
            w("%s.taskflow.json" % wf.name,
              json.dumps(generate_idmc_taskflow(wf), indent=2) + "\n")
        elif target == "scaffold":
            w("%s.pipeline.yml" % wf.name, generate_scaffold_yaml(wf))
        else:
            raise ValueError("Unknown orchestration target: %s (one of %s)"
                             % (target, ", ".join(ORCH_TARGETS)))
    return {"target": target, "files": written,
            "workflows": [wf.name for wf in cor.workflows]}
