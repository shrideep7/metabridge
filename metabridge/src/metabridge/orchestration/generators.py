def generate_scaffold_yaml(wf: Workflow) -> str:
    import yaml
    return yaml.safe_dump({
        "workflow": wf.name,
        "source_platform": wf.platform,
        "schedule": ([s.to_dict() for s in wf.schedules] or "manual"),
        "tasks": [t.to_dict() for t in wf.tasks],
        "dependencies": [d.to_dict() for d in wf.dependencies],
        "execution_waves": wf.execution_waves(),
        "notifications": [n.to_dict() for n in wf.notifications],
    }, sort_keys=False)


def generate_execution_doc(cor: COR, intelligence: dict,
                           validation: dict) -> str:
    lines = ["# Orchestration modernization — %s" % cor.name, "",
             "Source platform: **%s** · workflows: %d · tasks: %d"
             % (cor.source_platform, len(cor.workflows),
                sum(len(w.tasks) for w in cor.workflows)), "",
             "Automation score: **%s%%** · complexity: %s (%s) · "
             "estimated effort: %sh · validation: **%s**"
             % (intelligence["automation_score"],
                intelligence["migration_complexity"],
                intelligence["complexity_level"],
                intelligence["estimated_effort_hours"],
                validation["verdict"]), ""]
    for w in cor.workflows:
        lines += ["## %s" % w.name, ""]
        if w.schedules:
            lines.append("Schedule: " + "; ".join(
                s.raw or s.cron or s.kind for s in w.schedules))
        lines += ["", "Execution order:"]
        for i, wave in enumerate(w.execution_waves()):
            lines.append("%d. %s%s" % (
                i + 1, ", ".join(wave),
                "  *(parallel)*" if len(wave) > 1 else ""))
        fails = [(d.from_task, d.to_task) for d in w.dependencies
                 if d.kind == "failure"]
        if fails:
            lines += ["", "Failure paths: " + ", ".join(
                "%s → %s" % f for f in fails)]
        lines += ["", "```mermaid", to_mermaid(w), "```", ""]
    if intelligence["manual_review_items"]:
        lines += ["## Manual review", ""]
        for m in intelligence["manual_review_items"]:
            lines.append("- **%s** %s: %s" % (m.get("workflow", ""),
                                              m.get("code", ""),
                                              m.get("message", "")))
    return "\n".join(lines) + "\n"


