def generate_stepfunctions(wf: Workflow) -> dict:
    order = wf.execution_order()
    succ: Dict[str, List] = {}
    for d in wf.dependencies:
        succ.setdefault(d.from_task, []).append(d)
    states: Dict[str, dict] = {}
    for t in wf.tasks:
        st: Dict[str, object] = {}
        if t.type == "choice":
            choices, default = [], None
            for d in succ.get(t.key, []):
                if d.kind == "conditional" and d.condition != "default":
                    choices.append({"Variable": "$.condition",
                                    "IsPresent": True,
                                    "Next": d.to_task,
                                    "_metabridge_condition":
                                        d.condition[:200]})
                else:
                    default = d.to_task
            st = {"Type": "Choice", "Choices": choices or
                  [{"Variable": "$.ok", "BooleanEquals": True,
                    "Next": default or "Done_%s" % wf.name}]}
            if default:
                st["Default"] = default
        elif t.type == "wait":
            st = {"Type": "Wait",
                  "Seconds": int(t.action.get("seconds", 60) or 60)}
        elif t.type == "dummy":
            st = {"Type": "Pass"}
        else:
            st = {"Type": "Task",
                  "Resource": "arn:aws:states:::lambda:invoke",
                  "Parameters": {"FunctionName": "TODO_%s" % t.key,
                                 "_metabridge_action": t.action}}
            if t.retry.max_attempts:
                st["Retry"] = [{"ErrorEquals": ["States.ALL"],
                                "MaxAttempts": t.retry.max_attempts,
                                "IntervalSeconds":
                                    t.retry.interval_seconds or 10,
                                "BackoffRate":
                                    t.retry.backoff_factor or 2.0}]
            if t.timeout_seconds:
                st["TimeoutSeconds"] = t.timeout_seconds
        # linear Next from success edges (first one); Catch from failure
        if t.type != "choice":
            nexts = [d for d in succ.get(t.key, []) if d.kind == "success"]
            fails = [d for d in succ.get(t.key, []) if d.kind == "failure"]
            if nexts:
                st["Next"] = nexts[0].to_task
                for extra in nexts[1:]:
                    st.setdefault("_metabridge_note", []).append(
                        "also fans out to %s — model as Parallel"
                        % extra.to_task)
            else:
                st["End"] = True
            if fails and st.get("Type") == "Task":
                st["Catch"] = [{"ErrorEquals": ["States.ALL"],
                                "Next": f.to_task} for f in fails]
        states[t.key] = st
    return {"Comment": "Generated by MetaBridge AI from %s" % wf.platform,
            "StartAt": order[0] if order else "Done",
            "States": states}


