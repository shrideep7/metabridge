"""Orchestration target generators (Command 6, §5) — everything FROM COR.

    airflow          runnable DAG .py (schedule, retries, SLAs, task
                     groups for parallel waves, trigger rules for
                     failure paths, operator by task type)
    adf / fabric     pipeline JSON (activities + dependsOn conditions,
                     policy retry/timeout) + ScheduleTrigger JSON
    stepfunctions    ASL state machine (Retry/Catch, Choice, Parallel)
    controlm         Automation API JSON folder (events for deps)
    autosys          JIL (insert_job blocks, conditions, calendars)
    dbtcloud         job JSON (sequential steps + cron trigger)
    powercenter      workflow XML skeleton (tasks + links)
    idmc_taskflow    taskflow JSON (steps with onSuccess/onFailure)
    scaffold         pipeline scaffold YAML (engine-neutral)
    docs             execution documentation (markdown) + mermaid graph

Semantics that a target cannot express are written into the artifact as
explicit ``_metabridge_note`` fields / comments and surfaced as issues —
declared loss, never silent loss.
"""
from __future__ import annotations

import json
import re
from typing import Dict, List

from .cor import COR, Task, Workflow, normalize_cron
