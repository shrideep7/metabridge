def build_context(pipelines: Optional[list] = None, twin=None,
                  project: str = "", generated_at: str = "",
                  job_id: str = "", source_ref: str = "",
                  source_snapshot: str = "") -> dict:
    pipelines = pipelines or []
    if isinstance(pipelines, Pipeline):
        pipelines = [pipelines]
    if isinstance(twin, dict):
        twin = twin_from_dict(twin)
    if twin is None:
        twin = DigitalTwin(project or "estate")
    if not project:
        project = (pipelines[0].name if pipelines else twin.name) or "estate"
    return {"pipelines": pipelines, "twin": twin, "project": project,
            "generated_at": generated_at, "job_id": job_id,
            "source_ref": source_ref, "source_snapshot": source_snapshot}


def _meta(ctx: dict) -> dict:
    m = {"Project": ctx["project"],
         "Generated by": "MetaBridge AI"}
    if ctx.get("job_id"):
        m["Job ID"] = ctx["job_id"]
    if ctx.get("source_ref"):
        m["Source"] = ctx["source_ref"]
    if ctx["pipelines"]:
        fmts = sorted({p.source_format for p in ctx["pipelines"]
                       if p.source_format})
        if fmts:
            m["Source format"] = ", ".join(fmts)
    if ctx["generated_at"]:
        m["Generated"] = ctx["generated_at"]
    if ctx.get("source_snapshot"):
        m["Source snapshot"] = ctx["source_snapshot"]
    return m


def _all_mappings(ctx):
    return [(p, m) for p in ctx["pipelines"] for m in p.mappings]


def _xf(m):
    return [t for t in m.transformations if t.name != "__OUTPUT__"]


def _classifications(ctx):
    out = []
    try:
        from ..governance.engine import classify_pipeline
        for p in ctx["pipelines"]:
            out += [(p, c) for c in classify_pipeline(p)]
    except Exception:  # noqa: BLE001 — governance optional
        pass
    return out


def _empty_note(d: Doc, what: str) -> Doc:
    return d.note("No %s available in the analyzed metadata. Upload the "
                  "relevant project or build a Digital Twin to populate "
                  "this section." % what)


def _cap(d: Doc, items: list, cap: int, what: str) -> list:
    """Return at most ``cap`` items, and — critically — DISCLOSE the
    truncation in the document. A delivered document must never state a
    total and then silently list fewer (the product's own 'never
    silently dropped' principle)."""
    if len(items) > cap:
        d.note("Showing the first %d of %d %s. Generate the JSON export "
               "or narrow the scope for the complete set."
               % (cap, len(items), what))
        return items[:cap]
    return items


