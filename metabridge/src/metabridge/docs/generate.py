@_doc_type("solution_design", "Solution Design Document")
def gen_sdd(ctx) -> Doc:
    twin = ctx["twin"]
    d = Doc("Solution Design Document",
            "Target-state solution & modernization approach", _meta(ctx))
    d.h("Solution summary")
    n_map = sum(len(p.mappings) for p in ctx["pipelines"])
    n_src = sum(len(p.sources) for p in ctx["pipelines"])
    d.p("This solution modernizes %d pipeline object(s) reading from %d "
        "source table(s), catalogued across a %d-object estate graph."
        % (n_map, n_src, len(twin.nodes)))
    d.h("Design principles")
    d.bullets([
        "Single canonical intermediate representation — every source "
        "parses into it and every target generates from it (no pairwise "
        "converters).",
        "Honest degradation — anything that cannot be auto-translated is "
        "declared as a manual item, never silently dropped.",
        "Governance-first — sensitive data is classified and protected "
        "before it lands in the target.",
        "Deterministic, evidence-based analysis — figures trace to "
        "metadata or a labelled assumption."])
    d.h("Load strategies in scope")
    strat: Dict[str, int] = {}
    for p in ctx["pipelines"]:
        for m in p.mappings:
            strat[m.load_strategy.value] = \
                strat.get(m.load_strategy.value, 0) + 1
    if strat:
        d.table(["Load strategy", "Objects"],
                [[k, v] for k, v in sorted(strat.items(),
                                           key=lambda x: -x[1])])
    d.h("Manual-review items")
    from ..ir.model import IssueSeverity
    manual = [i for p in ctx["pipelines"] for i in p.all_issues()
              if i.severity in (IssueSeverity.MANUAL, IssueSeverity.ERROR)]
    if manual:
        d.p("%d item(s) require manual design decisions:" % len(manual))
        shown = _cap(d, manual, 20, "manual-review items")
        d.bullets(["[%s] %s — %s" % (i.severity.value, i.code, i.message)
                   for i in shown])
    else:
        d.p("No manual-review items — the solution is fully "
            "auto-translatable from the analyzed metadata.")
    return d


