"""Document generators.

Each generator composes what MetaBridge already knows — the parsed IR,
the Digital Twin, the governance classifier, lineage — into a canonical
Doc. Generators never render; the renderers in render.py turn a Doc into
PDF / Word / Markdown / HTML. Deterministic: no timestamps unless the
caller supplies one, so the same estate always produces byte-identical
documents.
"""
from __future__ import annotations

from typing import Dict, List, Optional

from ..ir.model import Pipeline, TransformationType
from ..twin.model import DigitalTwin, twin_from_dict
from .model import Doc

# slug -> (title, generator) — declaration order is the catalog order
DOC_TYPES: "Dict[str, tuple]" = {}


def _doc_type(slug, title):
    def deco(fn):
        DOC_TYPES[slug] = (title, fn)
        return fn
    return deco


