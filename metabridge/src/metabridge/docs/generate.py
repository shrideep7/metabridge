@_doc_type("migration_runbook", "Migration Runbook")
def gen_runbook(ctx) -> Doc:
    d = Doc("Migration Runbook",
            "Step-by-step migration execution & rollback", _meta(ctx))
    d.h("Pre-migration checklist")
    d.bullets([
        "Confirm target landing zone, connections and credentials "
        "(externalized in a secret manager).",
        "Snapshot source objects and record row counts for "
        "reconciliation.",
        "Freeze source schema changes for the cutover window.",
        "Provision CI/CD and a parallel-run environment."])
    if not ctx["pipelines"]:
        _empty_note(d, "pipeline execution order")
    for p in ctx["pipelines"]:
        waves = p.execution_order()
        if not waves:
            continue
        d.h("Execution waves — %s" % p.name, 2)
        d.p("Run each wave in order; every object in a wave may run in "
            "parallel. Reconcile row counts before advancing.")
        d.table(["Wave", "Objects", "Cutover note"],
                [[i + 1, ", ".join(w),
                  "parallel-run + reconcile" if i + 1 < len(waves)
                  else "final wave — decommission source after sign-off"]
                 for i, w in enumerate(waves)])
    d.h("Rollback")
    d.bullets([
        "Halt at the failed wave; the target is populated only up to the "
        "last reconciled wave.",
        "Re-point consumers to the source (parallel-run keeps it live).",
        "Preserve target artifacts + logs for root-cause before retry."])
    d.note("Confirm 'unused'/idle assets against runtime access logs "
           "before decommissioning any source.")
    return d


