@_doc_type("validation_report", "Validation Report")
def gen_validation(ctx) -> Doc:
    from ..ir.model import IssueSeverity
    d = Doc("Validation Report",
            "Parse & conversion-readiness validation", _meta(ctx))
    issues = [i for p in ctx["pipelines"] for i in p.all_issues()]
    by_sev: Dict[str, int] = {}
    for i in issues:
        by_sev[i.severity.value] = by_sev.get(i.severity.value, 0) + 1
    d.h("Summary")
    n_obj = sum(len(p.mappings) for p in ctx["pipelines"])
    d.kv([("Objects analyzed", str(n_obj)),
          ("Total issues", str(len(issues))),
          ("Errors", str(by_sev.get("ERROR", 0))),
          ("Manual", str(by_sev.get("MANUAL", 0))),
          ("Warnings", str(by_sev.get("WARNING", 0)))])
    blocking = [i for i in issues
                if i.severity in (IssueSeverity.ERROR,
                                  IssueSeverity.MANUAL)]
    if blocking:
        d.h("Blocking / manual items")
        shown = _cap(d, blocking, 60, "blocking / manual items")
        d.table(["Severity", "Object", "Code", "Message"],
                [[i.severity.value, i.obj or "—", i.code, i.message]
                 for i in shown])
    else:
        d.p("No blocking or manual items detected in the analyzed "
            "metadata.")
    d.note("This validates parse & conversion readiness from metadata. "
           "Full source-vs-target equivalence (schema, row counts, "
           "aggregates) requires running the generated target against "
           "sampled data.")
    return d


