@_doc_type("lineage_report", "Lineage Report")
def gen_lineage(ctx) -> Doc:
    from ..report import lineage as lin
    d = Doc("Lineage Report",
            "Table- and column-level data lineage", _meta(ctx))
    any_lin = False
    for p in ctx["pipelines"]:
        try:
            tl = lin.table_lineage(p)
        except Exception:  # noqa: BLE001
            tl = None
        edges = (tl or {}).get("edges") or []
        if edges:
            any_lin = True
            d.h("Table lineage — %s" % p.name, 2)
            shown = _cap(d, edges, 80, "table-lineage edges")
            d.table(["Source", "Target", "Via"],
                    [[e.get("from", e.get("source", "")),
                      e.get("to", e.get("target", "")),
                      e.get("mapping", e.get("via", ""))]
                     for e in shown])
    # column lineage summary from the twin flow edges as a fallback
    twin = ctx["twin"]
    flow = [(twin.nodes[e.from_id].name, e.kind, twin.nodes[e.to_id].name)
            for e in twin.edges.values()
            if e.kind in ("feeds", "writes", "reads", "produces",
                          "consumes")]
    if flow:
        any_lin = True
        d.h("Estate data flow")
        shown = _cap(d, flow, 120, "data-flow edges")
        d.table(["From", "Relationship", "To"],
                [[a, k, b] for a, k, b in shown])
    if not any_lin:
        _empty_note(d, "lineage")
    return d


