@_doc_type("governance_report", "Governance Report")
def gen_governance(ctx) -> Doc:
    d = Doc("Governance Report",
            "Data classification, policy & processing register",
            _meta(ctx))
    cls = _classifications(ctx)
    d.h("Classification summary")
    if cls:
        by_cat: Dict[str, int] = {}
        for _, c in cls:
            by_cat[c.category] = by_cat.get(c.category, 0) + 1
        special = sum(1 for _, c in cls
                      if c.category.startswith("pii.special"))
        d.kv([("Classified columns", str(len(cls))),
              ("Distinct categories", str(len(by_cat))),
              ("Special-category (GDPR Art.9)", str(special))])
        d.h("Classified columns", 2)
        shown = _cap(d, cls, 80, "classified columns")
        d.table(["Mapping", "Column", "Category", "GDPR", "HIPAA"],
                [[c.mapping, c.column, c.category, c.gdpr or "—",
                  c.hipaa or "—"] for _, c in shown])
    else:
        d.p("No sensitive columns detected by name heuristics.")
    # processing register (per pipeline)
    try:
        from ..governance.engine import govern
        reg_rows = []
        for p in ctx["pipelines"]:
            for a in govern(p).get("processing_register", []):
                if a.get("data_categories"):
                    reg_rows.append([a["activity"],
                                     ", ".join(a["source_systems"]),
                                     ", ".join(a["target_systems"]),
                                     ", ".join(a["data_categories"])])
        if reg_rows:
            d.h("Record of processing activities (Art.30 style)", 2)
            shown = _cap(d, reg_rows, 60, "processing activities")
            d.table(["Activity", "Sources", "Targets", "Data categories"],
                    shown)
    except Exception:  # noqa: BLE001
        pass
    d.note("Automated inventory from pipeline metadata — input for the "
           "DPO / privacy office, not legal advice.")
    return d


