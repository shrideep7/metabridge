@_doc_type("source_to_target_mapping", "Source-to-Target Mapping")
def gen_stm(ctx) -> Doc:
    d = Doc("Source-to-Target Mapping",
            "Column-level source-to-target field mapping", _meta(ctx))
    mappings = _all_mappings(ctx)
    if not mappings:
        return _empty_note(d, "pipeline mappings")
    for p, m in mappings:
        d.h("%s" % m.name, 2)
        srcs = [t for t in m.transformations
                if t.type == TransformationType.SOURCE]
        tgts = [t for t in m.transformations
                if t.type == TransformationType.TARGET]
        d.kv([("Load strategy", m.load_strategy.value),
              ("Sources", ", ".join(str(t.properties.get("table", t.name))
                                     for t in srcs) or "—"),
              ("Targets", ", ".join(str(t.properties.get("table", t.name))
                                     for t in tgts) or "—")])
        rows = []
        for t in tgts:
            for port in t.ports:
                rows.append([str(t.properties.get("table", t.name)),
                             port.name, port.datatype,
                             port.expression or "(pass-through)"])
        if rows:
            d.table(["Target table", "Target column", "Type",
                     "Derivation"], rows)
        else:
            d.p("No target columns declared for this mapping.")
    return d


