@_doc_type("architecture", "Architecture Document")
def gen_architecture(ctx) -> Doc:
    from ..twin import analyze
    twin = ctx["twin"]
    d = Doc("Architecture Document",
            "Current-state data estate architecture", _meta(ctx))
    d.h("Overview")
    counts = twin.counts()
    d.p("The data estate comprises %d catalogued object(s) across the "
        "layers below, discovered from the analyzed sources."
        % (len(twin.nodes)))
    if not twin.nodes:
        return _empty_note(d, "estate graph")
    d.kv([(k, v) for k, v in counts.items() if k != "edges"])

    d.h("Technology inventory")
    inv = analyze.technology_inventory(twin)
    if inv["technologies"]:
        d.table(["Technology", "Objects", "Breakdown"],
                [[t["technology"], t["total"],
                  ", ".join("%s: %d" % (k, v)
                            for k, v in t["by_kind"].items())]
                 for t in inv["technologies"]])
    d.h("Application landscape")
    land = analyze.application_landscape(twin)
    if land["applications"]:
        d.table(["Application", "Technology", "Domain", "Owner",
                 "Pipelines", "Tables", "Topics"],
                [[a["application"], a["technology"] or "—",
                  a["domain"], a["owner"] or "—", a["pipelines"],
                  a["tables"], a["topics"]]
                 for a in land["applications"]])
    else:
        d.p("No applications catalogued.")
    d.h("Application dependencies")
    dep = analyze.application_dependency_graph(twin)
    if dep["dependencies"]:
        d.table(["Application", "Depends on", "Via"],
                [[x["application"], x["depends_on"],
                  "; ".join(x["via"][:3])] for x in dep["dependencies"]])
    else:
        d.p("No cross-application data dependencies detected.")
    d.note("Architecture is derived from estate topology (the Digital "
           "Twin), not runtime telemetry.")
    return d


