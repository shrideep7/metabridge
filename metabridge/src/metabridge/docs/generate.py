def _type_str(port) -> str:
    """Column type including declared precision/scale when present."""
    dt = port.datatype
    if getattr(port, "precision", 0):
        if dt == "decimal":
            return "%s(%d,%d)" % (dt, port.precision, getattr(port, "scale", 0))
        return "%s(%d)" % (dt, port.precision)
    return dt


@_doc_type("data_dictionary", "Data Dictionary")
def gen_data_dictionary(ctx) -> Doc:
    from ..ir.model import TransformationType
    d = Doc("Data Dictionary",
            "Source & target tables, columns, types, lineage and "
            "transformation metadata", _meta(ctx))
    # column -> classification category (from governance)
    cls = {}
    for p, c in _classifications(ctx):
        cls[c.column.lower()] = c.category

    src_tables = 0
    tgt_tables = 0

    # --- Source tables ---------------------------------------------------
    d.h("Source tables", 2)
    seen = set()
    for p in ctx["pipelines"]:
        for s in p.sources:
            key = (s.database, s.schema, s.name)
            if key in seen:
                continue
            seen.add(key)
            src_tables += 1
            qualified = ".".join(x for x in (s.database, s.schema, s.name) if x)
            d.h(qualified, 3)
            if s.columns:
                d.table(["Column", "Type", "Nullable", "Classification"],
                        [[c.name, _type_str(c),
                          "yes" if c.nullable else "no",
                          cls.get(c.name.lower(), "—")]
                         for c in s.columns])
            else:
                d.p("No columns catalogued for this table (schema not "
                    "introspected).")
    if not src_tables:
        d.p("No source tables catalogued in the current project.")

    # --- Target tables (from each mapping's TARGET transformation) -------
    d.h("Target tables", 2)
    for p in ctx["pipelines"]:
        for m in p.mappings:
            for t in m.by_type(TransformationType.TARGET):
                tgt_tables += 1
                name = str(t.properties.get("table", t.name))
                d.h(name, 3)
                if t.ports:
                    d.table(["Column", "Type", "Nullable", "Key"],
                            [[c.name, _type_str(c),
                              "yes" if c.nullable else "no",
                              "PK" if c.name in m.unique_key else "—"]
                             for c in t.ports])
                else:
                    d.p("No target columns catalogued.")
    if not tgt_tables:
        d.p("No target tables catalogued in the current project.")

    # --- Transformation metadata + lineage -------------------------------
    d.h("Transformations & lineage", 2)
    any_mapping = False
    for p in ctx["pipelines"]:
        for m in p.mappings:
            any_mapping = True
            steps = [t for t in m.transformations if t.name != "__OUTPUT__"]
            srcs = [str(t.properties.get("table", t.name))
                    for t in m.by_type(TransformationType.SOURCE)]
            tgts = [str(t.properties.get("table", t.name))
                    for t in m.by_type(TransformationType.TARGET)]
            d.h(m.name, 3)
            rows = [
                ["Load strategy", getattr(m.load_strategy, "value",
                                          str(m.load_strategy))],
                ["Unique key", ", ".join(m.unique_key) or "—"],
                ["Sources", ", ".join(srcs) or "—"],
                ["Targets", ", ".join(tgts) or "—"],
                ["Depends on", ", ".join(m.depends_on) or "—"],
                ["Transformation steps",
                 ", ".join("%s(%s)" % (t.name, getattr(t.type, "value",
                                                       str(t.type)))
                           for t in steps) or "—"],
            ]
            d.kv(rows)
            if m.description:
                d.p(m.description)
    if not any_mapping:
        d.p("No transformations catalogued in the current project.")

    # --- Coverage / warning ----------------------------------------------
    if not (src_tables or tgt_tables or any_mapping):
        d.h("Coverage", 2)
        d.note("No table, column or transformation metadata was available in "
               "the analyzed project. This can happen when the upload has no "
               "column definitions or the source could not be parsed. Add "
               "column metadata to the manifest, or point the connector at "
               "the live system to introspect, then regenerate.")
    else:
        cov = ("Coverage: %d source table(s), %d target table(s), %d "
               "mapping(s)." % (src_tables, tgt_tables,
                                sum(len(p.mappings) for p in ctx["pipelines"])))
        missing = sum(1 for p in ctx["pipelines"] for s in p.sources
                      if not s.columns)
        if missing:
            cov += (" %d source table(s) have no column metadata — shown "
                    "without columns above." % missing)
        d.note(cov + " Classification is heuristic (column-name based) — "
               "confirm with a content scan before relying on it for "
               "compliance.")
    return d


