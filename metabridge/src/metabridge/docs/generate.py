@_doc_type("technical_design", "Technical Design Document")
def gen_tdd(ctx) -> Doc:
    d = Doc("Technical Design Document",
            "Per-object transformation design", _meta(ctx))
    mappings = _all_mappings(ctx)
    if not mappings:
        return _empty_note(d, "pipeline mappings")
    d.h("Execution order")
    for p in ctx["pipelines"]:
        waves = p.execution_order()
        if waves:
            d.p("%s:" % p.name)
            d.bullets(["Wave %d: %s" % (i + 1, ", ".join(w))
                       for i, w in enumerate(waves)])
    for p, m in mappings:
        d.h(m.name, 2)
        if m.description:
            d.p(m.description)
        d.kv([("Load strategy", m.load_strategy.value),
              ("Unique key", ", ".join(m.unique_key) or "—"),
              ("Depends on", ", ".join(m.depends_on) or "—"),
              ("Transformations", str(len(_xf(m))))])
        rows = []
        for t in _xf(m):
            detail = ""
            for k in ("condition", "join_type", "group_by", "sql_override",
                      "strategy"):
                v = t.properties.get(k)
                if v:
                    detail = "%s: %s" % (k, str(v)[:80])
                    break
            rows.append([t.name, t.type.value, detail or "—"])
        if rows:
            d.table(["Step", "Type", "Logic"], rows)
    return d


