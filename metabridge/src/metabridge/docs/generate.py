@_doc_type("business_glossary", "Business Glossary")
def gen_glossary(ctx) -> Doc:
    twin = ctx["twin"]
    d = Doc("Business Glossary",
            "Business domains, terms and ownership", _meta(ctx))
    domains = [n for n in twin.nodes.values() if n.kind == "domain"]
    products = [n for n in twin.nodes.values() if n.kind == "data_product"]
    if domains:
        d.h("Business domains")
        d.table(["Domain", "Owner", "Declared"],
                [[n.name, n.owner or "—",
                  "no (inferred)" if n.inferred else "yes"]
                 for n in sorted(domains, key=lambda x: x.name)])
    if products:
        d.h("Data products")
        d.table(["Data product", "Owner"],
                [[n.name, n.owner or "—"]
                 for n in sorted(products, key=lambda x: x.name)])
    # described objects double as glossary terms
    terms = []
    for p in ctx["pipelines"]:
        for m in p.mappings:
            if (m.description or "").strip():
                terms.append([m.name, m.description])
    if terms:
        d.h("Defined terms")
        d.table(["Term", "Definition"], terms)
    if not (domains or products or terms):
        _empty_note(d, "business domains, products or descriptions")
        d.note("Add an estate.yml descriptor (domains, owners, data "
               "products) and object descriptions to enrich the "
               "glossary.")
    return d


