def generate_document(slug: str, ctx: dict) -> Doc:
    if slug not in DOC_TYPES:
        raise ValueError("unknown document type: %s" % slug)
    return DOC_TYPES[slug][1](ctx)


def generate_all(ctx: dict, slugs: Optional[List[str]] = None
                 ) -> "Dict[str, Doc]":
    slugs = slugs or list(DOC_TYPES)
    return {s: generate_document(s, ctx) for s in slugs
            if s in DOC_TYPES}


def catalog() -> List[dict]:
    return [{"slug": s, "title": t} for s, (t, _) in DOC_TYPES.items()]
