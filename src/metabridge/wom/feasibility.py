"""Feasibility classification: every inventoried object, against a target.

Two sources of truth, combined:

  * **Evidence** where a definition exists — every view/materialized-view
    body is actually parsed with the source dialect and transpiled to the
    target dialect with sqlglot. A view is AUTOMATED because its SQL
    demonstrably converts, not because views are "usually fine".
  * **The matrix** for everything else — per (kind, language, target
    family): what the target equivalent is, whether the port is mechanical,
    reviewed, hand-written, or has no equivalent at all, and the effort a
    competent engineer needs.

Statuses:
    AUTOMATED      MetaBridge generates it; review is a formality
    PARTIAL        generated or directly mapped, but a human must review
    MANUAL         a known target pattern exists; a human writes it
    NO_EQUIVALENT  nothing on the target does this — declared loss/advisory

Effort figures are deterministic and explainable (hours per object by
class), the same contract as migration_intelligence — an estimate to plan
with, not a promise.
"""
