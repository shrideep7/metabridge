def _dialect_of(key: str) -> str:
    from ..connectors.base import get_registry
    spec = get_registry().get(key)
    if spec is not None and spec.dialect:
        return spec.dialect
    return SQL_DIALECT_FORMATS.get(key, "")


def _lookup(kind: str, language: str, target_family: str,
            source_key: str, target_key: str
            ) -> Tuple[str, str, float, str]:
    if source_key == target_key:
        return ("AUTOMATED", "unchanged (same platform)", 0.0, "")
    table = _LANG.get((kind, language)) or _M.get(kind) or {
        "*": ("MANUAL", "", 4.0, "Unrecognized object kind.")}
    return table.get(target_family) or table["*"]


_CREATE_VIEW_RE = re.compile(
    r"^\s*create\s+(or\s+replace\s+)?(secure\s+)?(recursive\s+)?"
    r"(materialized\s+|dynamic\s+table\b)?(view\b)?", re.I)
_IS_CREATE_RE = re.compile(r"^\s*create\b", re.I)


def transpile_view(defn: str, src_dialect: str, tgt_dialect: str,
                   qualified_name: str) -> Tuple[bool, str, str]:
    """(ok, target CREATE statement | "", reason). Evidence, not opinion:
    the body is genuinely parsed and re-rendered in the target dialect —
    and a parse that degrades to sqlglot's opaque Command node counts as
    FAILURE, because "kept the text verbatim" is not a conversion."""
    import sqlglot
    from sqlglot import exp
    text = (defn or "").strip().rstrip(";")
    if not text:
        return False, "", "definition not visible to the connected role"
    if _IS_CREATE_RE.match(text):
        body = re.sub(r"\bsecure\s+", "", text, flags=re.I)
    else:
        body = "CREATE VIEW %s AS %s" % (qualified_name, text)
    try:
        parsed = sqlglot.parse_one(body, read=src_dialect or None)
        if parsed is None or isinstance(parsed, exp.Command):
            return False, "", ("syntax the parser could not model — "
                               "convert by hand")
        # uniform, runnable output: every emitted view carries its schema,
        # whether the source stored a bare name or a qualified one
        if isinstance(parsed, exp.Create) and \
                isinstance(parsed.this, exp.Table) and \
                "." in qualified_name and not parsed.this.db:
            parsed.this.set("db", exp.to_identifier(
                qualified_name.split(".", 1)[0]))
        return True, parsed.sql(dialect=tgt_dialect or None,
                                pretty=True) + ";", ""
    except Exception as e:  # noqa: BLE001
        return False, "", str(e)[:180]


def classify_inventory(inv: ObjectInventory, source_key: str,
                       target_key: str) -> dict:
    """Every object -> a classification record; plus rollups and totals."""
    src_d = _dialect_of(source_key)
    tgt_d = _dialect_of(target_key)
    family = tgt_d or "*"
    records: List[dict] = []
    for o in inv.objects:
        status, equiv, hours, note = _lookup(o.kind, o.language, family,
                                             source_key, target_key)
        reason = note
        converted = ""
        if o.kind in ("view", "materialized_view") and \
                source_key != target_key:
            ok, sql, err = transpile_view(o.definition, src_d, tgt_d,
                                          o.qualified())
            if o.kind == "view":
                if ok:
                    status, hours = "AUTOMATED", 0.2
                    equiv = equiv or "CREATE VIEW"
                    reason = "definition transpiles cleanly to %s" % \
                        (tgt_d or target_key)
                    converted = sql
                else:
                    status, hours = "PARTIAL", 1.0
                    reason = "transpile: %s" % err
            else:                       # matrix status stands; add evidence
                if ok:
                    converted = sql
                    reason = (note + " " if note else "") + \
                        "Definition transpiles; refresh semantics need " \
                        "review."
                else:
                    reason = (note + " " if note else "") + \
                        "Transpile: %s" % err
        records.append({
            "kind": o.kind, "name": o.name, "schema": o.schema,
            "language": o.language, "status": status,
            "target_equivalent": equiv, "effort_hours": round(hours, 2),
            "reason": reason,
            **({"converted_sql": converted} if converted else {}),
        })

    by_status: Dict[str, int] = {}
    for r in records:
        by_status[r["status"]] = by_status.get(r["status"], 0) + 1
    total = len(records) or 1
    kinds: Dict[str, dict] = {}
    for r in records:
        k = kinds.setdefault(r["kind"], {
            "count": 0, "AUTOMATED": 0, "PARTIAL": 0, "MANUAL": 0,
            "NO_EQUIVALENT": 0, "effort_hours": 0.0,
            "target_equivalent": r["target_equivalent"]})
        k["count"] += 1
        k[r["status"]] += 1
        k["effort_hours"] = round(k["effort_hours"] + r["effort_hours"], 2)

    automated = by_status.get("AUTOMATED", 0)
    partial = by_status.get("PARTIAL", 0)
    return {
        "source": source_key, "target": target_key,
        "source_dialect": src_d, "target_dialect": tgt_d,
        "objects_total": len(records),
        "by_status": by_status,
        "automation_pct": round(100.0 * automated / total, 1),
        "automated_or_assisted_pct": round(
            100.0 * (automated + partial) / total, 1),
        "estimated_effort_hours": round(
            sum(r["effort_hours"] for r in records), 1),
        "kinds": {k: kinds[k] for k in sorted(kinds)},
        "records": records,
        "unreadable": inv.unreadable,
    }
