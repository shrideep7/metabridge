def _emit_workflow(folder: ET.Element, pipeline: Pipeline) -> None:
    wf_name = "wf_" + pipeline.name
    wf = ET.SubElement(folder, "WORKFLOW", {
        "NAME": wf_name, "DESCRIPTION": "MetaBridge AI-generated orchestration "
        "(sessions serialized by dbt DAG waves)", "ISENABLED": "YES",
        "ISVALID": "YES", "REUSABLE": "NO", "SUSPEND_ON_ERROR": "NO",
        "TASKS_MUST_RUN_ON_SERVER": "NO", "VERSIONNUMBER": "1",
    })
    ET.SubElement(wf, "SCHEDULER", {
        "NAME": "Scheduler", "REUSABLE": "NO", "VERSIONNUMBER": "1",
        "DESCRIPTION": "",
    })
    start = "Start"
    ET.SubElement(wf, "TASK", {"NAME": start, "TYPE": "Start",
                               "REUSABLE": "NO", "VERSIONNUMBER": "1", "DESCRIPTION": ""})

    strategies = {m.name: m for m in pipeline.mappings}
    for m in pipeline.mappings:
        s = ET.SubElement(wf, "SESSION", {
            "NAME": "s_m_" + m.name, "MAPPINGNAME": "m_" + m.name,
            "DESCRIPTION": "", "REUSABLE": "NO", "SORTORDER": "Binary",
            "VERSIONNUMBER": "1", "ISVALID": "YES",
        })
        treat = "Insert"
        if m.load_strategy in (LoadStrategy.MERGE, LoadStrategy.SCD2):
            treat = "Update else Insert"
        elif m.load_strategy == LoadStrategy.DELETE_INSERT:
            treat = "Data driven"
        ET.SubElement(s, "ATTRIBUTE", {"NAME": "Treat source rows as", "VALUE": treat})
        if m.load_strategy == LoadStrategy.FULL:
            ET.SubElement(s, "ATTRIBUTE", {"NAME": "Truncate target table option",
                                           "VALUE": "YES"})

    prev_wave: List[str] = [start]
    for wave in pipeline.execution_order():
        for name in wave:
            if name not in strategies:
                continue
            ET.SubElement(wf, "TASKINSTANCE", {
                "NAME": "s_m_" + name, "TASKNAME": "s_m_" + name,
                "TASKTYPE": "Session", "ISENABLED": "YES", "DESCRIPTION": "",
            })
        for src in prev_wave:
            for name in wave:
                ET.SubElement(wf, "WORKFLOWLINK", {
                    "FROMTASK": src if src == start else "s_m_" + src,
                    "TOTASK": "s_m_" + name,
                    "CONDITION": "" if src == start else
                    "$s_m_%s.Status = SUCCEEDED" % src,
                })
        prev_wave = wave
