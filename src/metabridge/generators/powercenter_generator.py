# PowerCenter's decimal tops out here unless the session enables high
# precision, so the shared fallback has to be clamped rather than copied.
_PC_MAX_DECIMAL = 28


def _pc_type(port: Port) -> Dict[str, str]:
    dtype, default_prec = _PC_TYPES.get(port.datatype, ("string", 255))
    prec = port.precision or default_prec
    scale = port.scale or 0
    if port.datatype == "decimal" and not port.precision:
        # An undeclared decimal is not an integer. Emitting SCALE="0" here
        # asserted it was, which contradicted the warehouse DDL for the same
        # column and would truncate every fractional value on import.
        prec, scale = decimal_fallback(_PC_MAX_DECIMAL)
    return {"DATATYPE": dtype, "PRECISION": str(prec), "SCALE": str(scale)}


def _emit_source_and_target_defs(folder: ET.Element, mapping: Mapping,
                                 pipeline: Pipeline, done: Dict[str, bool],
                                 src_dbtype: str = "ODBC",
                                 tgt_dbtype: str = "ODBC") -> None:
    for t in mapping.by_type(TransformationType.SOURCE):
        key = "SRC::" + str(t.properties.get("table", t.name))
        if key in done:
            continue
        done[key] = True
        src = ET.SubElement(folder, "SOURCE", {
            "NAME": str(t.properties.get("table", t.name)),
            "DATABASETYPE": _pc_dbtype(str(t.properties.get("database_type", "")))
            or src_dbtype,
            "DBDNAME": str(t.properties.get("database") or "SRC_DB"),
            "OWNERNAME": str(t.properties.get("schema") or ""),
            "DESCRIPTION": "", "BUSINESSNAME": "",
            "OBJECTVERSION": "1", "VERSIONNUMBER": "1",
        })
        for i, p in enumerate(t.ports, 1):
            tp = _pc_type(p)
            ET.SubElement(src, "SOURCEFIELD", {
                "NAME": p.name, "DATATYPE": tp["DATATYPE"],
                "PRECISION": tp["PRECISION"], "SCALE": tp["SCALE"],
                "FIELDNUMBER": str(i), "FIELDTYPE": "ELEMITEM",
                "KEYTYPE": "NOT A KEY", "NULLABLE": "NULL" if p.nullable else "NOTNULL",
                "LENGTH": "0", "LEVEL": "0", "OCCURS": "0", "OFFSET": "0",
                "PHYSICALLENGTH": tp["PRECISION"], "PHYSICALOFFSET": "0",
                "PICTURETEXT": "", "USAGE_FLAGS": "", "DESCRIPTION": "",
                "BUSINESSNAME": "", "FIELDPROPERTY": "0", "HIDDEN": "NO",
            })
    for t in mapping.by_type(TransformationType.TARGET):
        key = "TGT::" + str(t.properties.get("table", t.name))
        if key in done:
            continue
        done[key] = True
        tgt = ET.SubElement(folder, "TARGET", {
            "NAME": str(t.properties.get("table", t.name)),
            "DATABASETYPE": tgt_dbtype, "DESCRIPTION": "", "BUSINESSNAME": "",
            "CONSTRAINT": "", "TABLEOPTIONS": "",
            "OBJECTVERSION": "1", "VERSIONNUMBER": "1",
        })
        for p in t.ports:
            tp = _pc_type(p)
            attrs = {
                "NAME": p.name, "DATATYPE": tp["DATATYPE"],
                "PRECISION": tp["PRECISION"], "SCALE": tp["SCALE"],
                "KEYTYPE": "PRIMARY KEY" if p.name in mapping.unique_key else "NOT A KEY",
                "NULLABLE": "NULL" if p.nullable else "NOTNULL",
                "FIELDNUMBER": str(t.ports.index(p) + 1),
                "PICTURETEXT": "", "DESCRIPTION": "", "BUSINESSNAME": "",
            }
            ET.SubElement(tgt, "TARGETFIELD", attrs)


