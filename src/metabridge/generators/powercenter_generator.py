"""Generate PowerCenter repository XML (POWERMART) from the IR.

Produces one folder containing source/target definitions, one mapping per IR
mapping, and a workflow whose sessions follow the pipeline DAG (serialized by
topological waves).

Port expressions arrive as canonical ANSI SQL on IR ports and are translated
to the Informatica expression language here (late binding). Anything the rule
engine cannot translate is emitted as a pass-through port, the original SQL is
preserved in the port DESCRIPTION, and a MANUAL issue is raised — optionally
routed through the LLM assist callback first.
"""
from __future__ import annotations

import datetime
import re
import xml.etree.ElementTree as ET
from typing import Callable, Dict, List, Optional
from xml.dom import minidom

from ..ir.model import (
    IssueSeverity, LoadStrategy, Mapping, Pipeline, Port, Transformation,
    TransformationType,
)
from ..sqlx.expressions import ExpressionError, sql_to_infa
from ..sqlx.type_engine import decimal_fallback

# canonical -> (PC datatype, default precision)
_PC_TYPES = {
    "string": ("string", 255),
    "integer": ("integer", 10),
    "bigint": ("bigint", 19),
    "decimal": ("decimal", 28),
    "double": ("double", 15),
    "date": ("date/time", 29),
    "timestamp": ("date/time", 29),
    "boolean": ("integer", 1),
    "binary": ("binary", 4000),
}

_PC_TX_TYPE = {
    TransformationType.SOURCE_QUALIFIER: "Source Qualifier",
    TransformationType.EXPRESSION: "Expression",
    TransformationType.FILTER: "Filter",
    TransformationType.JOINER: "Joiner",
    TransformationType.AGGREGATOR: "Aggregator",
    TransformationType.SORTER: "Sorter",
    TransformationType.UNION: "Union Transformation",
    TransformationType.LOOKUP: "Lookup Procedure",
    TransformationType.ROUTER: "Router",
    TransformationType.RANK: "Rank",
    TransformationType.SEQUENCE: "Sequence",
    TransformationType.UPDATE_STRATEGY: "Update Strategy",
}

AssistFn = Optional[Callable[[str, str], Optional[str]]]  # (sql, context) -> infa expr

# Map a canonical dialect/platform to the PowerCenter DATABASETYPE label.
# Used so generated XML reflects the ACTUAL source/target platform instead
# of a hardcoded "Oracle" on every object.
_DIALECT_TO_PC_DBTYPE = {
    "oracle": "Oracle", "snowflake": "Snowflake",
    "teradata": "Teradata", "sqlserver": "Microsoft SQL Server",
    "mssql": "Microsoft SQL Server", "synapse": "Microsoft SQL Server",
    "postgres": "ODBC", "postgresql": "ODBC", "redshift": "ODBC",
    "bigquery": "ODBC", "databricks": "ODBC", "mysql": "ODBC",
    "db2": "DB2", "netezza": "Netezza",
}


def _pc_dbtype(value: str) -> str:
    """Resolve a PowerCenter DATABASETYPE from a connector's powercenter_dbtype,
    a dialect, or a platform name. Falls back to the neutral 'ODBC' — never
    silently 'Oracle' — when the platform is unknown."""
    v = (value or "").strip()
    if not v:
        return ""
    return _DIALECT_TO_PC_DBTYPE.get(v.lower(), v)


def generate_powercenter(pipeline: Pipeline, folder_name: str = "",
                         assist: AssistFn = None) -> str:
    """Return the POWERMART XML document as a string."""
    dialect = str(pipeline.metadata.get("dialect", ""))
    meta = pipeline.metadata
    # actual source/target database types — never a blanket Oracle default.
    # Only trust an explicit connector powercenter_dbtype or the SQL dialect;
    # source_platform/target_platform can be FORMAT names (dbt/idmc) which are
    # not valid DATABASETYPE values, so they are deliberately not used here.
    src_dbtype = (_pc_dbtype(str(meta.get("source_pc_dbtype", "")))
                  or _pc_dbtype(dialect) or "ODBC")
    tgt_dbtype = (_pc_dbtype(str(meta.get("target_pc_dbtype", "")))
                  or _pc_dbtype(dialect) or src_dbtype)
    repo_dbtype = tgt_dbtype or src_dbtype or "ODBC"
    root = ET.Element("POWERMART", {
        "CREATION_DATE": datetime.datetime.now().strftime("%m/%d/%Y %H:%M:%S"),
        "REPOSITORY_VERSION": "188.97",
    })
    repo = ET.SubElement(root, "REPOSITORY", {
        "NAME": "MetaBridge AI_Repo", "VERSION": "188", "CODEPAGE": "UTF-8",
        "DATABASETYPE": repo_dbtype,
    })
    folder = ET.SubElement(repo, "FOLDER", {
        "NAME": folder_name or pipeline.name, "GROUP": "", "OWNER": "metabridge",
        "SHARED": "NOTSHARED", "DESCRIPTION": "Generated by MetaBridge AI from %s project '%s'"
        % (pipeline.source_format or "dbt", pipeline.name), "PERMISSIONS": "rwx---r--",
    })

    emitted_defs: Dict[str, bool] = {}
    for mapping in pipeline.mappings:
        _emit_source_and_target_defs(folder, mapping, pipeline, emitted_defs,
                                     src_dbtype, tgt_dbtype)
    for mapping in pipeline.mappings:
        _emit_mapping(folder, mapping, dialect, assist)
    _emit_workflow(folder, pipeline)

    _scrub_control_chars(root)
    raw = ET.tostring(root, encoding="unicode")
    pretty = minidom.parseString(raw).toprettyxml(indent="  ")
    body = "\n".join(l for l in pretty.split("\n") if l.strip() and not l.startswith("<?xml"))
    return ('<?xml version="1.0" encoding="UTF-8"?>\n'
            '<!DOCTYPE POWERMART SYSTEM "powrmart.dtd">\n' + body + "\n")


# Characters XML 1.0 cannot represent AT ALL — not even as an entity. Tab,
# newline and carriage return are legal and are left alone.
_XML_ILLEGAL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")


def _scrub_control_chars(root: ET.Element) -> None:
    """Strip characters that would make the document unparseable.

    Expressions really do carry them: Oracle's INITCAP transpiles to an
    explicit delimiter set containing FORM FEED and VERTICAL TAB, and one such
    character anywhere makes the WHOLE workflow XML invalid — which used to
    take the rest of the scaffold's artifacts down with it. Replaced with a
    space rather than dropped, so a delimiter list keeps its arity.
    """
    for el in root.iter():
        for key, value in list(el.attrib.items()):
            if _XML_ILLEGAL.search(value):
                el.set(key, _XML_ILLEGAL.sub(" ", value))
        if el.text and _XML_ILLEGAL.search(el.text):
            el.text = _XML_ILLEGAL.sub(" ", el.text)


