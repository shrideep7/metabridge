def _to_infa(sql_expr: str, mapping: Mapping, context: str, dialect: str,
             assist: AssistFn) -> Optional[str]:
    try:
        return sql_to_infa(sql_expr, dialect)
    except ExpressionError as e:
        if assist is not None:
            result = assist(sql_expr, context)
            if result:
                mapping.add_issue(IssueSeverity.WARNING, "LLM_CONVERTED_EXPRESSION",
                                  "Expression converted by LLM assist — verify before deploy",
                                  detail="%s  =>  %s" % (sql_expr, result))
                mapping.issues[-1].resolved_by_llm = True
                return result
        mapping.add_issue(IssueSeverity.MANUAL, "EXPRESSION_UNCONVERTED",
                          "Expression could not be converted to Informatica (%s)" % context,
                          detail="%s | %s" % (sql_expr, e),
                          suggestion="Original SQL kept in the port description; "
                                     "rebuild manually or enable --llm-assist.")
        return None


def _emit_mapping(folder: ET.Element, mapping: Mapping, dialect: str,
                  assist: AssistFn) -> None:
    mname = "m_" + mapping.name
    mp = ET.SubElement(folder, "MAPPING", {
        "NAME": mname, "DESCRIPTION": mapping.description or
        "Converted from dbt model '%s' by MetaBridge AI" % mapping.name,
        "ISVALID": "YES", "OBJECTVERSION": "1", "VERSIONNUMBER": "1",
    })

    output_tx = mapping.transformation("__OUTPUT__")
    real_txs = [t for t in mapping.transformations
                if t.name != "__OUTPUT__" and t.type not in
                (TransformationType.SOURCE, TransformationType.TARGET)]

    for t in real_txs:
        _emit_transformation(mp, t, mapping, dialect, assist)

    # INSTANCE elements
    for t in mapping.by_type(TransformationType.SOURCE):
        ET.SubElement(mp, "INSTANCE", {
            "NAME": t.name, "TRANSFORMATION_NAME": str(t.properties.get("table", t.name)),
            "TRANSFORMATION_TYPE": "Source Definition", "TYPE": "SOURCE",
            "DBDNAME": str(t.properties.get("database") or "SRC_DB"),
            "DESCRIPTION": "", "REUSABLE": "NO",
        })
    for t in real_txs:
        ET.SubElement(mp, "INSTANCE", {
            "NAME": t.name, "TRANSFORMATION_NAME": t.name,
            "TRANSFORMATION_TYPE": _PC_TX_TYPE[t.type], "TYPE": "TRANSFORMATION",
            "DESCRIPTION": "", "REUSABLE": "NO",
        })
    for t in mapping.by_type(TransformationType.TARGET):
        ET.SubElement(mp, "INSTANCE", {
            "NAME": t.name, "TRANSFORMATION_NAME": str(t.properties.get("table", t.name)),
            "TRANSFORMATION_TYPE": "Target Definition", "TYPE": "TARGET",
            "DESCRIPTION": "", "REUSABLE": "NO",
        })

    # CONNECTORs — resolve the virtual __OUTPUT__ node into direct links
    tx_by_name = {t.name: t for t in mapping.transformations}
    upstream_of_output = str(output_tx.properties.get("upstream")) if output_tx else ""

    def instance_type(name: str) -> str:
        t = tx_by_name.get(name)
        if t is None:
            return "TRANSFORMATION"
        if t.type == TransformationType.SOURCE:
            return "Source Definition"
        if t.type == TransformationType.TARGET:
            return "Target Definition"
        return _PC_TX_TYPE[t.type]

    for link in mapping.links:
        frm, to = link.from_transformation, link.to_transformation
        if to == "__OUTPUT__":
            continue
        if frm == "__OUTPUT__":
            frm = upstream_of_output
        src_t, dst_t = tx_by_name.get(frm), tx_by_name.get(to)
        if src_t is None or dst_t is None:
            continue
        src_ports = {p.name.lower() for p in src_t.ports}
        for p in dst_t.ports:
            from_field = p.name
            if p.expression and dst_t.type in (TransformationType.EXPRESSION,
                                               TransformationType.AGGREGATOR):
                continue  # computed, not connected
            if from_field.lower() not in src_ports:
                continue
            ET.SubElement(mp, "CONNECTOR", {
                "FROMFIELD": from_field, "FROMINSTANCE": frm,
                "FROMINSTANCETYPE": instance_type(frm),
                "TOFIELD": p.name, "TOINSTANCE": to,
                "TOINSTANCETYPE": instance_type(to),
            })

    for i, t in enumerate(mapping.by_type(TransformationType.TARGET), 1):
        ET.SubElement(mp, "TARGETLOADORDER", {"ORDER": str(i), "TARGETINSTANCE": t.name})

    if mapping.load_strategy == LoadStrategy.SCD2:
        mapping.add_issue(IssueSeverity.MANUAL, "SCD2_TO_POWERCENTER",
                          "SCD Type 2 requires an effective-date mapping "
                          "(lookup on current version + update strategy + "
                          "insert of new version)",
                          suggestion="Use the Slowly Changing Dimension wizard "
                                     "or the workbook skeleton; generated "
                                     "mapping loads current state only.")
    if mapping.load_strategy in (LoadStrategy.MERGE, LoadStrategy.DELETE_INSERT,
                                 LoadStrategy.SCD2):
        ET.SubElement(mp, "MAPPINGVARIABLE", {
            "NAME": "$$LAST_RUN_TS", "DATATYPE": "date/time", "PRECISION": "29",
            "SCALE": "9", "ISPARAM": "NO", "AGGFUNCTION": "MAX",
            "DEFAULTVALUE": "01/01/1970 00:00:00", "DESCRIPTION":
            "Incremental watermark maintained by MetaBridge AI conversion",
        })


def _emit_transformation(mp: ET.Element, t: Transformation, mapping: Mapping,
                         dialect: str, assist: AssistFn) -> None:
    tx = ET.SubElement(mp, "TRANSFORMATION", {
        "NAME": t.name, "TYPE": _PC_TX_TYPE[t.type], "DESCRIPTION": t.description,
        "OBJECTVERSION": "1", "REUSABLE": "NO", "VERSIONNUMBER": "1",
    })
    group_by = [str(g).lower() for g in t.properties.get("group_by", [])] \
        if t.type == TransformationType.AGGREGATOR else []

    for p in t.ports:
        tp = _pc_type(p)
        attrs = {"NAME": p.name, **tp, "PORTTYPE": "INPUT/OUTPUT",
                 "DEFAULTVALUE": "", "DESCRIPTION": "", "PICTURETEXT": ""}
        if p.expression:
            infa = _to_infa(p.expression, mapping, "%s.%s" % (t.name, p.name),
                            dialect, assist)
            attrs["PORTTYPE"] = "OUTPUT"
            attrs["EXPRESSIONTYPE"] = "GENERAL"
            if infa is not None:
                attrs["EXPRESSION"] = infa
            else:
                attrs["EXPRESSION"] = p.name  # pass-through placeholder
                attrs["DESCRIPTION"] = "REVIEW — original SQL: " + p.expression
        elif t.type in (TransformationType.EXPRESSION, TransformationType.AGGREGATOR):
            attrs["EXPRESSION"] = p.name
            attrs["EXPRESSIONTYPE"] = "GENERAL"
        if group_by:
            attrs["EXPRESSIONTYPE"] = "GROUPBY" if p.name.lower() in group_by \
                else attrs.get("EXPRESSIONTYPE", "GENERAL")
        ET.SubElement(tx, "TRANSFORMFIELD", attrs)

    _emit_table_attributes(tx, t, mapping, dialect, assist)


def _attribute_safe_sql(sql: str, dialect: str) -> str:
    """XML attribute values normalize newlines to spaces on parse, so a
    multi-line override with `--` comments would swallow everything after the
    first comment. Emit a comment-free single-line statement instead."""
    try:
        import sqlglot
        out = sqlglot.transpile(sql, read=dialect or None, pretty=False,
                                comments=False)[0]
        return " ".join(out.split())
    except Exception:  # noqa: BLE001 — fall back to a textual scrub
        import re
        no_block = re.sub(r"/\*.*?\*/", " ", sql, flags=re.DOTALL)
        lines = [re.sub(r"--.*$", "", line) for line in no_block.splitlines()]
        return " ".join(" ".join(lines).split())


def _emit_table_attributes(tx: ET.Element, t: Transformation, mapping: Mapping,
                           dialect: str, assist: AssistFn) -> None:
    def attr(name: str, value: str) -> None:
        ET.SubElement(tx, "TABLEATTRIBUTE", {"NAME": name, "VALUE": value})

    if t.type == TransformationType.SOURCE_QUALIFIER:
        override = str(t.properties.get("sql_override", "") or "")
        if override:
            attr("Sql Query", _attribute_safe_sql(override, dialect))
    elif t.type == TransformationType.FILTER:
        cond = str(t.properties.get("condition", "TRUE"))
        infa = _to_infa(cond, mapping, "%s filter condition" % t.name, dialect, assist)
        attr("Filter Condition", infa if infa is not None else "TRUE -- REVIEW: " + cond)
    elif t.type == TransformationType.JOINER:
        jt = str(t.properties.get("join_type", "INNER"))
        pc_join = {"INNER": "Normal Join", "LEFT": "Master Outer Join",
                   "RIGHT": "Detail Outer Join", "FULL": "Full Outer Join"}.get(jt, "Normal Join")
        attr("Join Type", pc_join)
        cond = str(t.properties.get("condition", ""))
        infa = _to_infa(cond, mapping, "%s join condition" % t.name, dialect, assist) if cond else ""
        attr("Join Condition", infa or cond)
    elif t.type == TransformationType.SORTER:
        keys = t.properties.get("sort_keys", []) or []
        attr("Sort Keys", ", ".join("%s %s" % (k["port"], k["order"]) for k in keys))
        if t.properties.get("distinct"):
            attr("Distinct", "YES")
    elif t.type == TransformationType.LOOKUP:
        attr("Lookup table name", str(t.properties.get("table", "")))
        attr("Lookup condition", str(t.properties.get("condition", "")))


